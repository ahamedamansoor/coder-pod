// Get channels for a specific tag (max 15 channels for performance)
export function getChannelsForTag(tag: string): string[] {
  const categories = TAG_TO_CATEGORY[tag as keyof typeof TAG_TO_CATEGORY] || ['general'];
  
  const allChannels = new Set<string>();
  categories.forEach(category => {
    const channels = YOUTUBE_CHANNELS[category as keyof typeof YOUTUBE_CHANNELS] || [];
    channels.forEach(ch => allChannels.add(ch));
  });
  
  // Limit to 15 channels for performance (15 channels × 15 videos = 225 videos)
  return Array.from(allChannels).slice(0, 15);
}

